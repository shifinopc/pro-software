// Is this actually a section layout? Guards against a stored layout in an older/unknown shape, which
// would otherwise render as a blank page. Anything unrecognised falls back to the built-in design.
export const isSectionLayout = (l?: PrintLayoutDef | null): boolean =>
  !!l && Array.isArray(l.sections) && l.sections.some(s => s && typeof (s as any).id === "string" && typeof (s as any).show === "boolean");

// `inv` may carry extra client details (clientEmail/clientCity/clientPhone/clientCr) that the Billed To
// section can tick — the caller merges them in from the Client record.
// `layout` optional → falls back to the built-in builder so printing never breaks.
// Pick the engine that matches the stored layout's shape; anything unrecognised (or absent) prints
// the built-in design, so a bad layout can never produce a blank invoice.
function invoiceDoc(inv: InvoiceLike & Record<string, any>, layout?: any) {
  const d = invoiceFields(inv);
  if (isElementLayout(layout)) return renderElementsPDF(layout, d);
  if (isSectionLayout(layout)) return renderSectionsPDF(layout, d);
  return buildInvoicePDF(inv);
}

export function invoicePDF(inv: InvoiceLike & Record<string, any>, layout?: any) {
  invoiceDoc(inv, layout).save(`${inv.number}.pdf`);
}

// The same PDF as an object URL, for inline preview in an <iframe>.
// The caller owns the URL and must URL.revokeObjectURL() it when done.
export function invoicePDFUrl(inv: InvoiceLike & Record<string, any>, layout?: any): string {
  return URL.createObjectURL(invoiceDoc(inv, layout).output("blob"));
}

// Preview a free-form layout against sample data (the designer's "Preview PDF").
export function elementPreviewUrl(layout: ElementLayoutDef, data: Record<string, any>): string {
  return URL.createObjectURL(renderElementsPDF(layout, data).output("blob"));
}

// Preview any layout against sample data (the designer's "Preview PDF").
export function layoutPreviewUrl(layout: PrintLayoutDef, data: Record<string, any>): string {
  return URL.createObjectURL(renderSectionsPDF(layout, data).output("blob"));
}

// ── Generic table report PDF (compliance, clients, tasks, audit, reports…) ──
export function tableReportPDF(title: string, columns: string[], rows: (string | number)[][], filename: string) {
  const doc = new jsPDF(columns.length > 6 ? "landscape" : "portrait");
  const w = doc.internal.pageSize.getWidth();

  doc.setFillColor(...BRAND); doc.rect(0, 0, w, 22, "F");
  doc.setTextColor(255, 255, 255); doc.setFont("helvetica", "bold"); doc.setFontSize(14);
  doc.text("STIMES PRO", 14, 14);
  doc.setFont("helvetica", "normal"); doc.setFontSize(11);
  doc.text(title, w - 14, 14, { align: "right" });

  autoTable(doc, {
    startY: 30,
    head: [columns],
    body: rows.map(r => r.map(c => String(c ?? ""))),
    headStyles: { fillColor: BRAND },
    styles: { fontSize: 8, cellPadding: 2.5 },
    theme: "striped",
    didDrawPage: () => {
      doc.setFontSize(7); doc.setTextColor(160, 160, 160);
      doc.text(`${rows.length} records · generated ${title}`, 14, doc.internal.pageSize.getHeight() - 8);
    },
  });

  doc.save(filename);
}
