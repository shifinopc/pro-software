// ─────────────────────────────────────────────────────────────
// FREE-FORM ELEMENT ENGINE
// Place any field anywhere on the page. Each element carries its own position/size in millimetres
// (A4 = 210×297mm, which is jsPDF's native unit), so the designer canvas and the PDF share one
// coordinate space — what you position is exactly where it prints.
// ─────────────────────────────────────────────────────────────
export const PAGE_W = 210, PAGE_H = 297;
export type PrintElKind = "field" | "text" | "table" | "box" | "line";
export type PrintEl = {
  id: string;
  kind: PrintElKind;
  field?: string;          // data key — the dynamic bit
  text?: string;           // static text
  label?: string;          // small caption drawn above the value
  x: number; y: number; w: number; h?: number;   // mm
  size?: number; bold?: boolean; align?: "left" | "center" | "right"; color?: string;
  fill?: string;           // box only
  columns?: { key: string; label: string; align?: string }[]; // table only
};
export type ElementLayoutDef = { id?: string; name: string; target: string; elements: PrintEl[]; settings?: Record<string, any> };

export const isElementLayout = (l?: any): boolean =>
  !!l && Array.isArray(l.elements) && l.elements.some((e: any) => e && typeof e.x === "number" && typeof e.y === "number" && typeof e.kind === "string");

// Resolve the namespace an element's `field` binds to: the layout's own business details, overlaid
// with this document's data, plus money figures computed from the layout's VAT rate.
export function elementData(layout: ElementLayoutDef, data: Record<string, any>) {
  const st = layout.settings ?? {};
  const amt = Number(data.amountNum ?? 0);
  const vatRate = Number(st.vatRate ?? 0);
  const vat = amt * (vatRate / 100);
  const cur = String(data.currency || "SAR");
  const money = (n: number) => `${cur} ${n.toLocaleString(undefined, { maximumFractionDigits: 2 })}`;
  return {
    ...st, ...data,
    subtotal: money(amt),
    vat: money(vat),
    total: money(amt + vat),
    totalWords: amountInWords(amt + vat, cur),
  } as Record<string, any>;
}

export function renderElementsPDF(layout: ElementLayoutDef, raw: Record<string, any>) {
  const doc = new jsPDF(); // a4, millimetres
  const st = layout.settings ?? {};
  const data = elementData(layout, raw);
  const accent = hexToRgb(st.accent);
  const setColor = (hex?: string) => { const [r, g, b] = hexToRgb(hex ?? "#282828"); doc.setTextColor(r, g, b); };
  const anchorX = (el: PrintEl) => el.align === "center" ? el.x + el.w / 2 : el.align === "right" ? el.x + el.w : el.x;

  for (const el of [...(layout.elements ?? [])].sort((a, b) => (a.kind === "box" ? -1 : 0) - (b.kind === "box" ? -1 : 0))) {
    switch (el.kind) {
      case "box": {
        const [r, g, b] = el.fill === "accent" ? accent : hexToRgb(el.fill ?? "#eeeeee");
        doc.setFillColor(r, g, b);
        doc.rect(el.x, el.y, el.w, el.h ?? 10, "F");
        break;
      }
      case "line":
        doc.setDrawColor(...hexToRgb(el.color ?? "#c8c8c8"));
        doc.line(el.x, el.y, el.x + el.w, el.y);
        break;
      case "table": {
        const cols = el.columns ?? [];
        if (!cols.length) break;
        const rows: any[] = Array.isArray(data.items) && data.items.length ? data.items : [data];
        autoTable(doc, {
          startY: el.y,
          head: [cols.map(c => c.label)],
          body: rows.map(r => cols.map(c => { const v = (r as any)[c.key] ?? data[c.key]; return v == null ? "" : String(v); })),
          headStyles: { fillColor: accent, halign: "left" },
          columnStyles: Object.fromEntries(cols.map((c, i) => [i, { halign: (c.align as any) || (i === 0 ? "left" : "right") }])) as any,
          styles: { fontSize: el.size ?? 10, cellPadding: 3 },
          theme: (st.tableTheme as any) || "striped",
          margin: { left: el.x, right: PAGE_W - el.x - el.w },
          tableWidth: el.w,
        });
        break;
      }
      default: {
        // field | text
        const raw = el.kind === "field" ? data[el.field ?? ""] : el.text;
        const value = raw == null ? "" : String(raw);
        let y = el.y;
        if (el.label) {
          doc.setFont("helvetica", "normal"); doc.setFontSize(7); doc.setTextColor(150, 150, 150);
          doc.text(el.label.toUpperCase(), anchorX(el), y + 2.5, { align: el.align ?? "left" });
          y += 5;
        }
        if (!value) break;
        const size = el.size ?? 10;
        doc.setFont("helvetica", el.bold ? "bold" : "normal");
        doc.setFontSize(size);
        setColor(el.color === "accent" ? undefined : el.color);
        if (el.color === "accent") doc.setTextColor(...accent);
        const lines = doc.splitTextToSize(value, Math.max(el.w, 4));
        doc.text(lines, anchorX(el), y + size * 0.36, { align: el.align ?? "left" });
      }
    }
  }
  return doc;
}

