import jsPDFImport from "jspdf";
import autoTableImport from "jspdf-autotable";

// Bundlers hand back the constructor directly; Node's ESM interop hands back the namespace. Resolve
// once so this module also runs outside the browser (server-side rendering, tests).
const jsPDF: typeof jsPDFImport = (jsPDFImport as any)?.default ?? jsPDFImport;
const autoTable: typeof autoTableImport = (autoTableImport as any)?.default ?? autoTableImport;

const BRAND: [number, number, number] = [113, 5, 239]; // #7105ef

export type InvoiceLike = {
  number: string; client: string; amount: number; currency?: string;
  status: string; date?: string; dueDate?: string; services?: string;
};

// ── Professional invoice PDF (built-in fallback) ──
// Builds the document without deciding what to do with it, so the exact same PDF can be either
// downloaded or previewed inline. Used whenever no custom layout has been designed.
function buildInvoicePDF(inv: InvoiceLike) {
  const doc = new jsPDF();
  const cur = inv.currency || "SAR";
  const w = doc.internal.pageSize.getWidth();

  doc.setFillColor(...BRAND);
  doc.rect(0, 0, w, 28, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold"); doc.setFontSize(18);
  doc.text("STIMES PRO", 14, 18);
  doc.setFont("helvetica", "normal"); doc.setFontSize(10);
  doc.text("PRO & Compliance Services", 14, 24);
  doc.setFont("helvetica", "bold"); doc.setFontSize(22);
  doc.text("INVOICE", w - 14, 18, { align: "right" });

  doc.setTextColor(40, 40, 40);
  doc.setFont("helvetica", "bold"); doc.setFontSize(11);
  doc.text(inv.number, w - 14, 40, { align: "right" });
  doc.setFont("helvetica", "normal"); doc.setFontSize(9); doc.setTextColor(110, 110, 110);
  if (inv.date) doc.text(`Issued: ${inv.date}`, w - 14, 46, { align: "right" });
  if (inv.dueDate) doc.text(`Due: ${inv.dueDate}`, w - 14, 51, { align: "right" });
  doc.text(`Status: ${inv.status.toUpperCase()}`, w - 14, 56, { align: "right" });

  doc.setTextColor(150, 150, 150); doc.setFontSize(8);
  doc.text("BILL TO", 14, 42);
  doc.setTextColor(40, 40, 40); doc.setFont("helvetica", "bold"); doc.setFontSize(12);
  doc.text(inv.client, 14, 49);

  autoTable(doc, {
    startY: 66,
    head: [["Description", "Amount"]],
    body: [[inv.services || "Professional services", `${cur} ${inv.amount.toLocaleString()}`]],
    headStyles: { fillColor: BRAND, halign: "left" },
    columnStyles: { 1: { halign: "right", cellWidth: 45 } },
    styles: { fontSize: 10, cellPadding: 4 },
    theme: "striped",
  });

  const y = (doc as any).lastAutoTable.finalY + 10;
  doc.setDrawColor(230, 230, 230); doc.line(w - 90, y, w - 14, y);
  doc.setFont("helvetica", "bold"); doc.setFontSize(13); doc.setTextColor(...BRAND);
  doc.text("Total", w - 90, y + 9);
  doc.text(`${cur} ${inv.amount.toLocaleString()}`, w - 14, y + 9, { align: "right" });

  doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(150, 150, 150);
  doc.text("Thank you for your business. Generated by STIMES PRO.", 14, doc.internal.pageSize.getHeight() - 12);

  return doc;
}

// ─────────────────────────────────────────────────────────────
// SECTION-BASED PRINT LAYOUT ENGINE
// A layout is the document's real sections (Billed By, Items, Totals…). Each section can be shown or
// hidden, and within it you tick which fields print — no template tokens. The same renderer drives
// the designer preview and the real download, so what you design is what prints.
// ─────────────────────────────────────────────────────────────
export type PrintField = { key: string; label: string; show: boolean };
export type PrintSectionId = "header" | "meta" | "billedBy" | "billedTo" | "items" | "totals" | "terms" | "notes" | "signature" | "footer";
export type PrintSection = { id: PrintSectionId; show: boolean; title?: string; fields?: PrintField[]; columns?: PrintField[] };
export type PrintLayoutDef = {
  id?: string; name: string; target: string;
  sections: PrintSection[];
  // Layout-level content the admin types once (own business details, terms, footer) — as opposed to
  // per-document data, which arrives in `data`.
  settings?: Record<string, any>;
};

const ones = ["", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen"];
const tens = ["", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety"];
function words(n: number): string {
  if (!isFinite(n) || n < 0) return "";
  if (n < 20) return ones[n];
  if (n < 100) return (tens[Math.floor(n / 10)] + (n % 10 ? "-" + ones[n % 10] : "")).trim();
  if (n < 1000) return (ones[Math.floor(n / 100)] + " hundred" + (n % 100 ? " " + words(n % 100) : "")).trim();
  const units: [number, string][] = [[1e9, "billion"], [1e6, "million"], [1e3, "thousand"]];
  for (const [v, name] of units) {
    if (n >= v) return (words(Math.floor(n / v)) + " " + name + (n % v ? " " + words(n % v) : "")).trim();
  }
  return String(n);
}
export const amountInWords = (n: number, cur = "SAR") => {
  const whole = Math.floor(Math.abs(n));
  const s = words(whole) || "zero";
  return `${cur} ${s.charAt(0).toUpperCase() + s.slice(1)} only`;
};

const hexToRgb = (hex?: string): [number, number, number] => {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(hex ?? "").trim());
  if (!m) return BRAND;
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const on = (sec: PrintSection | undefined, key: string) => !!sec?.fields?.find(f => f.key === key)?.show;
const labelOf = (sec: PrintSection | undefined, key: string, dflt = "") => sec?.fields?.find(f => f.key === key)?.label ?? dflt;

export function renderSectionsPDF(layout: PrintLayoutDef, data: Record<string, any>) {
  const st = layout.settings ?? {};
  const doc = new jsPDF();
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 14;
  const accent = hexToRgb(st.accent);
  const sec = (id: PrintSectionId) => layout.sections?.find(s => s.id === id && s.show);
  const val = (k: string) => { const v = data[k]; return v == null ? "" : String(v); };
  let y = M;

  // ── Header band ──
  const h = sec("header");
  if (h) {
    const bh = Number(st.headerHeight) || 28;
    doc.setFillColor(...accent); doc.rect(0, 0, W, bh, "F");
    doc.setTextColor(255, 255, 255);
    if (on(h, "orgName")) { doc.setFont("helvetica", "bold"); doc.setFontSize(18); doc.text(String(st.orgName || "STIMES PRO"), M, bh - 10); }
    if (on(h, "tagline")) { doc.setFont("helvetica", "normal"); doc.setFontSize(10); doc.text(String(st.tagline || ""), M, bh - 4); }
    if (on(h, "docTitle")) { doc.setFont("helvetica", "bold"); doc.setFontSize(22); doc.text(String(h.title || "INVOICE"), W - M, bh - 10, { align: "right" }); }
    y = bh + 12;
  }

  // ── Meta (number / dates / status) — right column ──
  const meta = sec("meta");
  let metaBottom = y;
  if (meta) {
    let my = y;
    (meta.fields ?? []).filter(f => f.show).forEach(f => {
      doc.setFont("helvetica", "normal"); doc.setFontSize(9); doc.setTextColor(120, 120, 120);
      doc.text(`${f.label}:`, W - M - 42, my, { align: "right" });
      doc.setFont("helvetica", "bold"); doc.setTextColor(40, 40, 40);
      doc.text(val(f.key), W - M, my, { align: "right" });
      my += 5.5;
    });
    metaBottom = my;
  }

  // ── Billed By / Billed To ──
  const by = sec("billedBy"), to = sec("billedTo");
  const partyBlock = (s: PrintSection | undefined, x: number, source: "settings" | "data") => {
    if (!s) return y;
    let py = y;
    doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(150, 150, 150);
    doc.text(String(s.title || "").toUpperCase(), x, py); py += 6;
    let first = true;
    (s.fields ?? []).filter(f => f.show).forEach(f => {
      const v = source === "settings" ? String(st[f.key] ?? "") : val(f.key);
      if (!v) return;
      const head = first; first = false;
      doc.setFont("helvetica", head ? "bold" : "normal");
      doc.setFontSize(head ? 12 : 9);
      doc.setTextColor(head ? 40 : 110, head ? 40 : 110, head ? 40 : 110);
      doc.splitTextToSize(v, 76).forEach((ln: string) => { doc.text(ln, x, py); py += head ? 6 : 4.6; });
    });
    return py;
  };
  const yl = partyBlock(by, M, "settings");
  const yr = partyBlock(to, W / 2 + 4, "data");
  y = Math.max(yl, yr, metaBottom) + 6;

  // ── Items table (only ticked columns) ──
  const items = sec("items");
  if (items) {
    const cols = (items.columns ?? []).filter(c => c.show);
    if (cols.length) {
      const rows: any[] = Array.isArray(data.items) && data.items.length ? data.items : [data];
      autoTable(doc, {
        startY: y,
        head: [cols.map(c => c.label)],
        body: rows.map(r => cols.map(c => { const v = (r as any)[c.key] ?? data[c.key]; return v == null ? "" : String(v); })),
        headStyles: { fillColor: accent, halign: "left" },
        columnStyles: Object.fromEntries(cols.map((_c, i) => [i, { halign: i === 0 ? "left" : "right" }])) as any,
        styles: { fontSize: 10, cellPadding: 4 },
        theme: (st.tableTheme as any) || "striped",
        margin: { left: M, right: M },
      });
      y = (doc as any).lastAutoTable.finalY + 8;
    }
  }

  // ── Totals ──
  const tot = sec("totals");
  if (tot) {
    const amt = Number(data.amountNum ?? 0);
    const vatRate = Number(st.vatRate ?? 0);
    const vat = amt * (vatRate / 100);
    const cur = String(data.currency || "SAR");
    const money = (n: number) => `${cur} ${n.toLocaleString(undefined, { maximumFractionDigits: 2 })}`;
    const lines: [string, string, boolean][] = [
      [labelOf(tot, "subtotal", "Subtotal"), money(amt), on(tot, "subtotal")],
      [`${labelOf(tot, "vat", "VAT")} (${vatRate}%)`, money(vat), on(tot, "vat")],
      [labelOf(tot, "total", "Total"), money(on(tot, "vat") ? amt + vat : amt), on(tot, "total")],
    ];
    const shown = lines.filter(l => l[2]);
    if (shown.length) {
      doc.setDrawColor(230, 230, 230); doc.line(W - 90, y, W - M, y); y += 7;
      shown.forEach(([lb, v], i) => {
        const last = i === shown.length - 1;
        doc.setFont("helvetica", last ? "bold" : "normal"); doc.setFontSize(last ? 13 : 10);
        if (last) doc.setTextColor(...accent); else doc.setTextColor(90, 90, 90);
        doc.text(lb, W - 90, y); doc.text(v, W - M, y, { align: "right" });
        y += last ? 9 : 6;
      });
    }
    if (on(tot, "totalWords")) {
      doc.setFont("helvetica", "italic"); doc.setFontSize(8); doc.setTextColor(120, 120, 120);
      doc.text(amountInWords(on(tot, "vat") ? amt + vat : amt, String(data.currency || "SAR")), W - M, y, { align: "right" }); y += 7;
    }
  }

  // ── Terms / Notes ──
  for (const id of ["terms", "notes"] as PrintSectionId[]) {
    const s = sec(id);
    if (!s) continue;
    const body = String(st[id === "terms" ? "termsText" : "notesText"] ?? "");
    if (!body) continue;
    y += 4;
    doc.setFont("helvetica", "bold"); doc.setFontSize(9); doc.setTextColor(40, 40, 40);
    doc.text(String(s.title || (id === "terms" ? "Terms & Conditions" : "Notes")), M, y); y += 5;
    doc.setFont("helvetica", "normal"); doc.setFontSize(8.5); doc.setTextColor(110, 110, 110);
    doc.splitTextToSize(body, W - M * 2).forEach((ln: string) => { doc.text(ln, M, y); y += 4.4; });
  }

  // ── Signature ──
  const sig = sec("signature");
  if (sig) {
    const sy = Math.min(y + 16, H - 34);
    doc.setDrawColor(180, 180, 180); doc.line(W - M - 55, sy, W - M, sy);
    doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(120, 120, 120);
    doc.text(String(sig.title || "Authorised Signatory"), W - M, sy + 5, { align: "right" });
  }

  // ── Footer ──
  if (sec("footer")) {
    doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(150, 150, 150);
    doc.text(String(st.footerText || ""), M, H - 12);
  }
  return doc;
}

